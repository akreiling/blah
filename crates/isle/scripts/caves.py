"""Real-window cave cues and light boundaries, using genomes actually spawned in generated Deeps.

The scoped reload fixtures isolate each encounter: only position, other inhabitants, and stun change.
They do not invent genes or bypass the real keyboard handlers when hiding and walking.
"""

import copy
import json
import pathlib
import tempfile

from isle import Isle, sighted
from smoke import route


def traits(creature):
    g = creature["wild"]["genome"]
    return {"tremorsense": g[1] >= 0.6 and 0.4 <= g[2] < 0.8,
            "luminous": g[2] >= 0.8 and g[4] >= 0.5}


def safe(level, pos):
    return any(max(abs(pos[0] - s[0]), abs(pos[1] - s[1])) <= 2
               for s in [level["stairs_up"], level["stairs_down"]])


def isolation(save, level, creature):
    """Keep a natural inhabitant and find a straight, unobstructed light-boundary crossing beside it."""
    x, y = creature["pos"]
    for dx, dy, inward, outward in [(1, 0, "left", "right"), (-1, 0, "right", "left"),
                                    (0, 1, "up", "down"), (0, -1, "down", "up")]:
        cells = [(x + dx * n, y + dy * n) for n in range(4)]
        if all(0 <= a < 64 and 0 <= b < 32 and level["terrain"][b][a] == "." and not safe(level, (a, b))
               for a, b in cells):
            save = copy.deepcopy(save)
            made = copy.deepcopy(creature)
            made["stunned"] = 100
            save["creatures"], save["spawns"] = [made], []
            save["wild_ready"] = 2**64 - 1
            save["player"]["pos"] = list(cells[2])
            save["player"]["hidden"] = False
            return save, inward, outward
    return None


def caves():
    found = {}
    with tempfile.TemporaryDirectory(prefix="isle-caves-", dir="/tmp") as directory:
        path = pathlib.Path(directory) / "save.json"
        # Each floor's wildlife is generated by an actual stair command. Reloads move only to the
        # previous floor's lower landing so searching several floors doesn't require fighting them.
        for seed in range(1, 9):
            with Isle(seed=seed) as isle:
                reply = isle.batch("Wren\n", map="rows", game=True)
                level = reply["map"]
                isle.batch(*route(level, tuple(reply["game"]["player"]["pos"]), tuple(level["stairs_down"])),
                           interrupt=False)
                reply = isle.batch(">", map="rows", game=True)
                assert isle.quit() == 0
            for depth in range(1, 7):
                save, level = reply["game"], reply["map"]
                for c in save["creatures"]:
                    if c["at"] != save["player"]["at"] or not c["wild"]:
                        continue
                    for trait, enabled in traits(c).items():
                        fixture = isolation(save, level, c) if enabled and trait not in found else None
                        if fixture:
                            found[trait] = fixture
                if len(found) == 2 or depth == 6:
                    break
                save["player"]["pos"] = level["stairs_down"]
                path.write_text(json.dumps(save))
                with Isle(save=path) as isle:
                    reply = isle.batch(">", map="rows", game=True)
                    assert isle.quit() == 0
            if len(found) == 2:
                break
        assert set(found) == {"tremorsense", "luminous"}, "both adaptations occur in generated Deep inhabitants"
        for trait, (save, inward, outward) in found.items():
            path.write_text(json.dumps(save))
            with Isle(save=path) as isle:
                seen = sighted(isle.screen())
                assert len(seen) == 1 and trait in seen[0][3], seen
                if trait == "luminous":
                    assert "lit · no hiding" in isle.screen()["panel"]
                    reply = isle.batch("hide\n", game=True)
                    assert not reply["game"]["player"]["hidden"]
                    assert any("glow" in n["text"].lower() for n in reply["news"]), reply["news"]
                    isle.batch(outward)
                    assert "lit · no hiding" not in isle.screen()["panel"]
                    for _ in range(12):
                        reply = isle.batch("hide\n", game=True)
                        if reply["game"]["player"]["hidden"]:
                            break
                    assert reply["game"]["player"]["hidden"], "hiding works outside the glow"
                    reply = isle.batch(inward, game=True)
                    assert not reply["game"]["player"]["hidden"]
                    assert "lit · no hiding" in isle.screen()["panel"]
                saved = isle.request("state", game=True)["game"]
                assert isle.quit() == 0
            with Isle(save=path) as isle:
                assert isle.request("state", game=True)["game"] == saved
                assert trait in sighted(isle.screen())[0][3]
                assert isle.quit() == 0
    print("PASS caves: naturally spawned trait cues, glow blocks hiding only nearby, walking reveals, exact reload")


if __name__ == "__main__":
    caves()
